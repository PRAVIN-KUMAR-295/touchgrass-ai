"""Mission API endpoints."""

from datetime import datetime, timezone
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.orm import Session
from app.core.database import get_db
from app.core.models import Mission
from app.schemas.mission import MissionCreateRequest, MissionResponse
from app.schemas.plan import GeneratedMissionResponse
from app.services.mission_service import MissionGenerationService

router = APIRouter(prefix="/missions", tags=["Missions"])
mission_service = MissionGenerationService()


@router.post("", response_model=MissionResponse, status_code=status.HTTP_201_CREATED)
async def create_mission(
    payload: MissionCreateRequest,
    db: Session = Depends(get_db),
):
    """
    Validate mission preferences, create a mission record in SQLite,
    and return the created mission awaiting generation.
    """
    mission = Mission(
        duration_minutes=payload.duration_minutes,
        activity_type=payload.activity_type,
        difficulty=payload.difficulty,
        mode=payload.mode,
        status="pending_generation",
    )
    db.add(mission)
    db.commit()
    db.refresh(mission)

    response_data = MissionResponse.model_validate(mission)
    response_data.message = "Mission created. Ready for AI generation."
    return response_data


@router.post("/{mission_id}/generate", response_model=GeneratedMissionResponse)
async def generate_mission_content(
    mission_id: str,
    db: Session = Depends(get_db),
):
    """
    Generate outdoor mission content using Gemma or graceful fallback,
    validate safety and schema, persist results, and return full mission plan.
    """
    mission = db.query(Mission).filter(Mission.id == mission_id).first()
    if not mission:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Mission with ID '{mission_id}' not found",
        )

    preferences = {
        "duration_minutes": mission.duration_minutes,
        "activity_type": mission.activity_type,
        "difficulty": mission.difficulty,
        "mode": mission.mode,
    }

    # Generate via AI or fallback
    plan, provider_name, is_fallback = await mission_service.generate_mission(preferences)

    # Persist generated content
    mission.title = plan.title
    mission.steps = plan.steps
    mission.safety_note = plan.safety_note
    mission.ai_provider = provider_name
    mission.status = "ready"
    db.commit()
    db.refresh(mission)

    return GeneratedMissionResponse(
        id=mission.id,
        duration_minutes=mission.duration_minutes,
        activity_type=mission.activity_type,
        difficulty=mission.difficulty,
        mode=mission.mode,
        status=mission.status,
        title=mission.title,
        steps=mission.steps,
        safety_note=mission.safety_note,
        ai_provider=mission.ai_provider,
        is_fallback=is_fallback,
        message=(
            "Outdoor mission generated by Gemma."
            if not is_fallback
            else "Using ready-made mission while AI is unavailable."
        ),
    )


@router.post("/{mission_id}/start", response_model=MissionResponse)
async def start_mission(
    mission_id: str,
    db: Session = Depends(get_db),
):
    """
    Transition mission from 'ready' to 'in_progress', recording started_at in UTC.
    """
    mission = db.query(Mission).filter(Mission.id == mission_id).first()
    if not mission:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Mission with ID '{mission_id}' not found",
        )

    if mission.status == "in_progress":
        return MissionResponse.model_validate(mission)

    if mission.status == "completed":
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Cannot start an already completed mission.",
        )

    if mission.status == "pending_generation" or not mission.steps:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Mission does not have generated content yet. Generate mission before starting.",
        )

    # Set started_at and status
    mission.started_at = datetime.now(timezone.utc)
    mission.status = "in_progress"
    db.commit()
    db.refresh(mission)

    response_data = MissionResponse.model_validate(mission)
    response_data.message = "Mission started. Put your phone away and go!"
    return response_data


@router.post("/{mission_id}/complete", response_model=MissionResponse)
async def complete_mission(
    mission_id: str,
    db: Session = Depends(get_db),
):
    """
    Transition mission from 'in_progress' to 'completed', recording completed_at in UTC.
    """
    mission = db.query(Mission).filter(Mission.id == mission_id).first()
    if not mission:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Mission with ID '{mission_id}' not found",
        )

    if mission.status == "completed":
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Mission is already marked completed.",
        )

    if mission.status != "in_progress":
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Cannot complete a mission with status '{mission.status}'. Mission must be started first.",
        )

    mission.completed_at = datetime.now(timezone.utc)
    mission.status = "completed"
    db.commit()
    db.refresh(mission)

    response_data = MissionResponse.model_validate(mission)
    response_data.message = "Mission complete. You spent time outside. Nice."
    return response_data


@router.get("", response_model=List[MissionResponse])
async def list_missions(
    status_filter: Optional[str] = Query(None, alias="status"),
    db: Session = Depends(get_db),
):
    """
    Return existing missions, ordered newest first. Optionally filter by status.
    """
    query = db.query(Mission)
    if status_filter:
        query = query.filter(Mission.status == status_filter)

    missions = query.order_by(Mission.created_at.desc()).all()
    return [MissionResponse.model_validate(m) for m in missions]
